import { readFileSync } from 'node:fs';
import { call, must, log, state, save } from './lib.mjs';
import { encodeConstructor } from '../../capital-lib.js';
const CO = 'fc-studio';
const src = readFileSync(new URL('../../contracts/src/AgentShares.sol', import.meta.url), 'utf8');
const comp = must(await call(null, 'POST', '/api/v1/contracts/compile', { source: src, filename: 'AgentShares.sol' }), 'compile');
const k = comp.contracts.find((c) => c.name === 'AgentShares');
const w = async (id) => (await call(id, 'GET', `/api/v1/agents/${id}/wallet`)).wallet.address;
const coWallet = await w(CO), f1 = await w('funny'), f2 = await w('charisma');
const p = { companyId: CO, name: 'FC Studio shares', symbol: 'FCS', cash: '0x036CbD53842c5426634e7929541eC2318f3dCF7e', operator: coWallet, treasury: coWallet, price: 1000n, sharesForSale: 2n, founders: [f1, f2], founderShares: [2n, 2n] };
const args = [p.companyId, p.name, p.symbol, p.cash, p.operator, p.treasury, '1000', '2', p.founders, ['2', '2']];
const prep = must(await call(null, 'POST', '/api/v1/contracts/prepare-deploy', { abi: k.abi, bytecode: k.bytecode, args }), 'prepare');
const mine = k.bytecode + encodeConstructor(p);
if (prep.deployment.data.toLowerCase() !== mine.toLowerCase()) throw new Error('prepare-deploy encoding differs from capital-lib');
log(`compiled AgentShares with handoff's solc ${comp.version}; constructor: FC Studio shares (FCS), price 0.001 USDC a share, 2 for sale, founders funny ${f1} and charisma ${f2} with 2 each, operator and treasury ${CO}'s wallet ${coWallet}`);
const d = must(await call(CO, 'POST', '/api/v1/contracts/deploy', { abi: k.abi, bytecode: k.bytecode, args }), 'deploy');
if (!d.deployed) throw new Error('not deployed: ' + JSON.stringify(d).slice(0, 300));
state.shares = { address: d.address, block: d.block, tx: d.tx, abi: k.abi }; save();
log(`${CO} deployed its share contract through POST /contracts/deploy: ${d.address} block ${d.block} tx ${d.tx}`, { deploy: { ...d } });
